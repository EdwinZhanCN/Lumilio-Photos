const atlasDir = "docs/atlas"

const generatedHeader = "<!-- Generated by `task atlas:generate` from docs/atlas and source. Do not edit. -->\n\n"

// generatedFiles renders every checked-in markdown file, keyed by repo path.
func (a *Atlas) generatedFiles() map[string][]byte {
	files := map[string][]byte{}
	for _, view := range a.Views {
		files[path.Join(atlasDir, "generated", view.Category, view.ID+".md")] = a.viewMarkdown(view)
	}
	files[path.Join(atlasDir, "generated", "modules.md")] = a.modulesMarkdown()
	files[path.Join(atlasDir, "generated", "README.md")] = a.indexMarkdown()
	return files
}

func sourceLink(from, file string, line int) string {
	if file == "" {
		return ""
	}
	depth := strings.Count(path.Dir(from), "/") + 1
	target := strings.Repeat("../", depth) + file
	label := file
	if line > 0 {
		target += fmt.Sprintf("#L%d", line)
		label += fmt.Sprintf(":%d", line)
	}
	return fmt.Sprintf("[`%s`](%s)", label, target)
}

func tableCell(text string) string {
	return strings.ReplaceAll(strings.ReplaceAll(strings.TrimSpace(text), "|", "\\|"), "\n", " ")
}

func (a *Atlas) anchorCell(from, anchor string) string {
	if anchor == "" {
		return ""
	}
	resolved := a.Anchors[anchor]
	if resolved == nil {
		return "`" + anchor + "`"
	}
	if resolved.File == "" {
		return "`" + anchor + "`"
	}
	return "`" + anchor + "` " + sourceLink(from, resolved.File, resolved.Line)
}

func (a *Atlas) viewMarkdown(view *View) []byte {
	from := path.Join(atlasDir, "generated", view.Category, view.ID+".md")
	var b bytes.Buffer
	b.WriteString(generatedHeader)
	fmt.Fprintf(&b, "# %s\n\n", view.Title)
	fmt.Fprintf(&b, "_%s · source: `%s`_\n\n", view.Category, view.Source)
	fmt.Fprintf(&b, "%s\n\n", strings.TrimSpace(view.Summary))
	fmt.Fprintf(&b, "```mermaid\n%s```\n\n", a.mermaid(view, false))
	switch view.Kind {
	case "sequence":
		b.WriteString("## Participants\n\n| Participant | Anchor |\n| --- | --- |\n")
		for _, node := range view.Nodes {
			fmt.Fprintf(&b, "| %s | %s |\n", tableCell(node.Label), a.anchorCell(from, node.Anchor))
		}
		b.WriteString("\n## Steps\n\n| # | From → To | Message | Anchor |\n| --- | --- | --- | --- |\n")
		for _, row := range sequenceRows(view) {
			label := row.Label
			if row.Block != "" {
				label = "_" + row.Block + "_ — " + label
			}
			fmt.Fprintf(&b, "| %d | %s → %s | %s | %s |\n", row.Number, row.From, row.To, tableCell(label), a.anchorCell(from, row.Anchor))
		}
	case "lifecycle":
		if view.Enum != "" {
			fmt.Fprintf(&b, "States are exactly the members of %s.\n\n", a.anchorCell(from, view.Enum))
		}
		b.WriteString("## States\n\n| State | Meaning | Anchor |\n| --- | --- | --- |\n")
		for _, node := range view.Nodes {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", tableCell(node.Label), tableCell(node.Note), a.anchorCell(from, node.Anchor))
		}
		b.WriteString("\n## Transitions\n\n| From | To | Trigger | Anchor |\n| --- | --- | --- | --- |\n")
		for _, transition := range view.Transitions {
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", transition.From, transition.To, tableCell(transition.Label), a.anchorCell(from, transition.Anchor))
		}
	default:
		b.WriteString("## Elements\n\n| Element | Description | Anchor |\n| --- | --- | --- |\n")
		for _, node := range view.Nodes {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", tableCell(node.Label), tableCell(node.Note), a.anchorCell(from, node.Anchor))
		}
		var anchoredEdges []Edge
		for _, edge := range view.Edges {
			if edge.Anchor != "" {
				anchoredEdges = append(anchoredEdges, edge)
			}
		}
		if len(anchoredEdges) > 0 {
			b.WriteString("\n## Anchored flows\n\n| From → To | Label | Anchor |\n| --- | --- | --- |\n")
			for _, edge := range anchoredEdges {
				fmt.Fprintf(&b, "| %s → %s | %s | %s |\n", edge.From, edge.To, tableCell(edge.Label), a.anchorCell(from, edge.Anchor))
			}
		}
	}
	for _, note := range view.Notes {
		fmt.Fprintf(&b, "\n## %s\n\n%s\n", note.Title, strings.TrimSpace(note.Body))
	}
	if len(view.Related) > 0 {
		b.WriteString("\n## Related views\n\n")
		for _, related := range view.Related {
			for _, other := range a.Views {
				if other.ID == related {
					fmt.Fprintf(&b, "- [%s](../%s/%s.md)\n", other.Title, other.Category, other.ID)
				}
			}
		}
	}
	return b.Bytes()
}

func (a *Atlas) modulesMarkdown() []byte {
	from := path.Join(atlasDir, "generated", "modules.md")
	var b bytes.Buffer
	b.WriteString(generatedHeader)
	b.WriteString("# Module catalog\n\nEvery Go package and Web module, its group, and its one-line purpose. The full description lives in the linked `doc.go` or `doc.ts`.\n")
	layers := groupLayers(a.Config.Groups)
	for _, side := range sides {
		fmt.Fprintf(&b, "\n## %s\n", side.Title)
		groups := a.groupsOnSide(side.ID)
		sort.SliceStable(groups, func(i, j int) bool { return layers[groups[i].ID] > layers[groups[j].ID] })
		for _, group := range groups {
			fmt.Fprintf(&b, "\n### %s (`%s`)\n\n%s\n\n", group.Title, group.ID, strings.TrimSpace(group.Summary))
			if len(group.Uses) > 0 {
				fmt.Fprintf(&b, "Uses: %s\n\n", "`"+strings.Join(group.Uses, "`, `")+"`")
			}
			b.WriteString("| Module | Purpose | Doc |\n| --- | --- | --- |\n")
			for _, module := range a.sortedModules() {
				if module.Group == group.ID {
					fmt.Fprintf(&b, "| `%s` | %s | %s |\n", module.ID, tableCell(module.Synopsis), sourceLink(from, module.DocFile, 0))
				}
			}
		}
	}
	return b.Bytes()
}

func (a *Atlas) indexMarkdown() []byte {
	var b bytes.Buffer
	b.WriteString(generatedHeader)
	b.WriteString("# Lumilio Atlas — generated index\n\nBrowse interactively with `task atlas`. How the Atlas works and how to author views: [../README.md](../README.md). Module catalog: [modules.md](modules.md).\n")
	titles := map[string]string{"architecture": "Architecture", "sequence": "Sequence", "dataflow": "Data flow", "lifecycle": "Lifecycle"}
	for _, kind := range viewKinds {
		fmt.Fprintf(&b, "\n## %s\n\n", titles[kind])
		for _, view := range a.Views {
			if view.Category != kind || (view.Derived && strings.HasPrefix(view.ID, "group-")) {
				continue
			}
			summary := strings.TrimSpace(view.Summary)
			if dot := strings.Index(summary, ". "); dot > 0 {
				summary = summary[:dot+1]
			}
			fmt.Fprintf(&b, "- [%s](%s/%s.md) — %s\n", view.Title, view.Category, view.ID, tableCell(summary))
		}
		if kind == "architecture" {
			b.WriteString("\nGroup package views:")
			for _, view := range a.Views {
				if view.Derived && strings.HasPrefix(view.ID, "group-") {
					fmt.Fprintf(&b, " [%s](architecture/%s.md) ·", strings.TrimPrefix(view.ID, "group-"), view.ID)
				}
			}
			b.Truncate(b.Len() - 2)
			b.WriteString("\n")
		}
	}
	return b.Bytes()
}

// lockFile returns the verified hash of every code anchor in authored views.
func (a *Atlas) lockFile() []byte {
	lock := map[string]map[string]string{}
	for viewID, anchors := range a.viewAnchors {
		for anchor := range anchors {
			if resolved := a.Anchors[anchor]; resolved != nil && resolved.Hash != "" {
				if lock[viewID] == nil {
					lock[viewID] = map[string]string{}
				}
				lock[viewID][anchor] = resolved.Hash
			}
		}
	}
	data, _ := json.MarshalIndent(lock, "", "  ")
	return append(data, '\n')
}

func writeFiles(root string, files map[string][]byte) error {
	for rel, data := range files {
		target := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(target, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// pruneGenerated deletes generated markdown that no longer has a view.
func pruneGenerated(root string, files map[string][]byte) error {
	base := filepath.Join(root, atlasDir, "generated")
	return filepath.Walk(base, func(current string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return nil
		}
		rel := filepath.ToSlash(mustRel(root, current))
		if _, ok := files[rel]; !ok {
			return os.Remove(current)
		}
		return nil
	})
}

// outdatedGenerated lists generated files whose checked-in bytes differ.
func outdatedGenerated(root string, files map[string][]byte) []string {
	var outdated []string
	for rel, data := range files {
		existing, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil || !bytes.Equal(existing, data) {
			outdated = append(outdated, rel)
		}
	}
	base := filepath.Join(root, atlasDir, "generated")
	_ = filepath.Walk(base, func(current string, info os.FileInfo, err error) error {
		if err == nil && !info.IsDir() {
			if _, ok := files[filepath.ToSlash(mustRel(root, current))]; !ok {
				outdated = append(outdated, filepath.ToSlash(mustRel(root, current))+" (orphaned)")
			}
		}
		return nil
	})
	sort.Strings(outdated)
	return outdated
}

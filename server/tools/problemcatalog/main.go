// Command problemcatalog publishes the stable documentation behind Lumilio's
// RFC 9457 type URI namespace.
package main

import (
	"fmt"
	"html/template"
	"os"
	"path/filepath"
	"strings"

	"server/internal/api/problem"
)

type pageData struct {
	Descriptor problem.Descriptor
	Path       string
}

var pageTemplate = template.Must(template.New("problem").Parse(`<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <title>{{.Descriptor.Title}} · Lumilio API Problem</title>
  <style>body{max-width:52rem;margin:4rem auto;padding:0 1.5rem;font:16px/1.6 system-ui,sans-serif;color:#202124}code{background:#f3f4f6;padding:.15rem .35rem;border-radius:.25rem}dt{font-weight:700;margin-top:1rem}dd{margin-left:0}table{border-collapse:collapse;width:100%}th,td{text-align:left;border-bottom:1px solid #ddd;padding:.6rem}</style>
</head>
<body>
  <p><a href="/problems/">Lumilio API Problems</a></p>
  <h1>{{.Descriptor.Title}}</h1>
  <dl>
    <dt>Type</dt><dd><code>{{.Descriptor.Type}}</code></dd>
    <dt>Normal HTTP status</dt><dd>{{.Descriptor.Status}}</dd>
    <dt>Definition</dt><dd>{{.Descriptor.Definition}}</dd>
    <dt>Recovery</dt><dd>{{.Descriptor.Recovery}}</dd>
    <dt>Recovery entry</dt><dd>actor <code>{{.Descriptor.Entry.Actor}}</code>, phase <code>{{.Descriptor.Entry.Phase}}</code>, kind <code>{{.Descriptor.Entry.Kind}}</code>{{if .Descriptor.Entry.Route}}, route <code>{{.Descriptor.Entry.Route}}</code>{{end}}{{if .Descriptor.Entry.HostAction}}, host action <code>{{.Descriptor.Entry.HostAction}}</code>{{end}}</dd>
  </dl>
  <h2>Extension members</h2>
  {{if .Descriptor.Extensions}}<table><thead><tr><th>Name</th><th>Schema</th><th>Meaning</th></tr></thead><tbody>{{range .Descriptor.Extensions}}<tr><td><code>{{.Name}}</code></td><td>{{.Schema}}</td><td>{{.Description}}</td></tr>{{end}}</tbody></table>{{else}}<p>This Problem type defines no extension members.</p>{{end}}
  <p>Runtime clients identify this condition by <code>type</code>; they do not dereference this page automatically.</p>
</body>
</html>
`))

var indexTemplate = template.Must(template.New("index").Parse(`<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Lumilio API Problems</title><style>body{max-width:52rem;margin:4rem auto;padding:0 1.5rem;font:16px/1.6 system-ui,sans-serif;color:#202124}code{background:#f3f4f6;padding:.15rem .35rem;border-radius:.25rem}li{margin:.7rem 0}</style></head>
<body><h1>Lumilio API Problems</h1><p>Stable RFC 9457 Problem type documentation for the Lumilio API.</p><ul>{{range .}}<li><a href="/problems/{{.Path}}/"><code>{{.Descriptor.Type}}</code></a> — {{.Descriptor.Definition}}</li>{{end}}</ul></body></html>
`))

func main() {
	if len(os.Args) != 3 {
		panic("usage: problemcatalog OUTPUT_DIRECTORY WEB_RECOVERY_REGISTRY_FILE")
	}
	output := filepath.Clean(os.Args[1])
	webRegistry := filepath.Clean(os.Args[2])
	if filepath.Base(output) != "problems" {
		panic("output directory must end in problems")
	}
	if err := os.RemoveAll(output); err != nil {
		panic(err)
	}
	if err := os.MkdirAll(output, 0o755); err != nil {
		panic(err)
	}

	descriptors := problem.Registered()
	pages := make([]pageData, 0, len(descriptors))
	for _, descriptor := range descriptors {
		path := strings.TrimPrefix(descriptor.Type, problem.Namespace)
		page := pageData{Descriptor: descriptor, Path: path}
		pages = append(pages, page)
		directory := filepath.Join(output, filepath.FromSlash(path))
		if err := os.MkdirAll(directory, 0o755); err != nil {
			panic(err)
		}
		write(filepath.Join(directory, "index.html"), pageTemplate, page)
	}
	write(filepath.Join(output, "index.html"), indexTemplate, pages)
	if err := os.WriteFile(webRegistry, []byte(webRecoveryRegistry(descriptors)), 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("Published %d Problem type pages in %s and the Web recovery registry %s.\n", len(pages), output, webRegistry)
}

// webRecoveryRegistry renders the executable recovery registry the Web
// consumes: one entry per public Problem type, in registry order, typed
// against the generated OpenAPI union so a type the Server adds without an
// entry here fails the Web type check.
func webRecoveryRegistry(descriptors []problem.Descriptor) string {
	var b strings.Builder
	b.WriteString("// Generated by `task dto` (server/tools/problemcatalog) from the Server's Problem\n")
	b.WriteString("// registry. Do not edit: change server/internal/api/problem/problem.go and regenerate.\n")
	b.WriteString("import type { KnownProblemType } from \"./problem\";\n\n")
	b.WriteString("export type RecoveryActor = \"user\" | \"admin\" | \"operator\" | \"desktop_host\";\n")
	b.WriteString("export type RecoveryPhase = \"any\" | \"setup\" | \"running\";\n")
	b.WriteString("export type RecoveryKind = \"retry\" | \"sign_in\" | \"route\" | \"host_action\" | \"operator\" | \"none\";\n\n")
	b.WriteString("/**\n * The executable recovery of one Problem type: who acts, in which phase, and\n * through which real entry. A `route` is a Web route pattern whose\n * `:repositoryId` segment is filled from the Problem's repository_id; a\n * `host_action` is started from `route` and approved on the Desktop host.\n */\n")
	b.WriteString("export type RecoveryEntry = {\n  readonly actor: RecoveryActor;\n  readonly phase: RecoveryPhase;\n  readonly kind: RecoveryKind;\n  readonly route?: string;\n  readonly hostAction?: string;\n};\n\n")
	b.WriteString("export const PROBLEM_RECOVERY = {\n")
	b.WriteString("  \"about:blank\": { actor: \"user\", phase: \"any\", kind: \"retry\" },\n")
	for _, descriptor := range descriptors {
		entry := descriptor.Entry
		fmt.Fprintf(&b, "  %q: { actor: %q, phase: %q, kind: %q", descriptor.Type, entry.Actor, entry.Phase, entry.Kind)
		if entry.Route != "" {
			fmt.Fprintf(&b, ", route: %q", entry.Route)
		}
		if entry.HostAction != "" {
			fmt.Fprintf(&b, ", hostAction: %q", entry.HostAction)
		}
		b.WriteString(" },\n")
	}
	b.WriteString("} as const satisfies Record<KnownProblemType, RecoveryEntry>;\n")
	return b.String()
}

func write(path string, tmpl *template.Template, value any) {
	file, err := os.Create(path)
	if err != nil {
		panic(err)
	}
	if err := tmpl.Execute(file, value); err != nil {
		_ = file.Close()
		panic(err)
	}
	if err := file.Close(); err != nil {
		panic(err)
	}
}

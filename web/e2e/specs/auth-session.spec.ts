import { readFileSync } from "node:fs";
import type { APIRequestContext, APIResponse } from "playwright/test";
import { expect, test, type Workspace } from "../fixtures/test";
import { LoginPage } from "../pages/login.page";
import { t } from "../support/i18n";
import type { components } from "../../src/lib/http-commons/schema.d.ts";

type AuthResponse = {
  token: string;
  csrfToken: string;
  user: {
    user_id: number;
    username: string;
  };
};

// Derived from the generated OpenAPI types rather than hand-written, so a
// browse-contract change breaks the build instead of failing at runtime.
type QueryResponse = components["schemas"]["dto.QueryAssetsResponseDTO"];

type UploadResponse = {
  receipt_id: string;
  status: string;
};

type UploadOperationStatus = {
  receipt_id: string;
  status: string;
  terminal: boolean;
  success: boolean;
  error?: string;
};

type UploadOperationStatusResponse = {
  operations?: UploadOperationStatus[];
};

async function expectAuth(response: APIResponse): Promise<AuthResponse> {
  if (!response.ok()) {
    expect(response.ok(), await response.text()).toBe(true);
  }
  const auth = (await response.json()) as AuthResponse;
  expect(auth.token).toBeTruthy();
  expect(auth.csrfToken).toBeTruthy();
  expect(auth.user.username).toBeTruthy();
  expect((auth as AuthResponse & { refreshToken?: string }).refreshToken).toBeUndefined();
  expect(response.headers()["set-cookie"]).toContain("lumilio_refresh=");
  expect(response.headers()["set-cookie"]).toContain("HttpOnly");
  return auth;
}

async function login(request: APIRequestContext, workspace: Workspace): Promise<AuthResponse> {
  return expectAuth(
    await request.post("/api/v1/auth/login", {
      data: {
        username: workspace.username,
        password: workspace.password,
      },
    }),
  );
}

async function refresh(request: APIRequestContext, csrfToken: string): Promise<APIResponse> {
  return request.post("/api/v1/auth/refresh", {
    headers: { "x-csrf-token": csrfToken },
  });
}

async function refreshWithCredential(
  request: APIRequestContext,
  refreshToken: string,
  csrfToken: string,
): Promise<APIResponse> {
  return request.post("/api/v1/auth/refresh", {
    headers: {
      cookie: `lumilio_refresh=${refreshToken}`,
      "x-csrf-token": csrfToken,
    },
  });
}

async function apiRefreshCookie(request: APIRequestContext): Promise<string> {
  const state = await request.storageState();
  const cookie = state.cookies.find((candidate) => candidate.name === "lumilio_refresh");
  if (!cookie) throw new Error("API context did not retain the HttpOnly refresh cookie");
  return cookie.value;
}

async function register(
  request: APIRequestContext,
  username: string,
  password: string,
): Promise<AuthResponse> {
  return expectAuth(
    await request.post("/api/v1/auth/register/start", {
      data: { username, password },
    }),
  );
}

async function uploadAsset(
  request: APIRequestContext,
  workspace: Workspace,
  filename: string,
): Promise<string> {
  const source = readFileSync(workspace.authIsolationSource);
  const endOfImage = source.lastIndexOf(Buffer.from([0xff, 0xd9]));
  if (endOfImage < 0) throw new Error("auth isolation fixture is not a JPEG");

  // Preserve the real source image while inserting a valid JPEG comment. This
  // gives repeated local/CI runs distinct content hashes without replacing the
  // representative test asset with generated bytes.
  const marker = Buffer.from(`lumilio-e2e:${filename}`, "utf8");
  const markerLength = marker.length + 2;
  const uniqueSource = Buffer.concat([
    source.subarray(0, endOfImage),
    Buffer.from([0xff, 0xfe, markerLength >> 8, markerLength & 0xff]),
    marker,
    source.subarray(endOfImage),
  ]);
  const response = await request.post("/api/v1/assets", {
    headers: { authorization: `Bearer ${workspace.token}` },
    multipart: {
      repository_id: workspace.repositoryId,
      file: {
        name: filename,
        mimeType: "image/jpeg",
        buffer: uniqueSource,
      },
    },
  });
  expect(response.ok(), await response.text()).toBe(true);
  const upload = (await response.json()) as UploadResponse;
  expect(upload.status).toBe("processing");
  expect(upload.receipt_id).toMatch(/^[0-9a-f-]{36}$/);
  return upload.receipt_id;
}

async function uploadOperationStatus(
  request: APIRequestContext,
  token: string,
  receiptId: string,
): Promise<UploadOperationStatus | undefined> {
  const response = await request.get(`/api/v1/assets/batch/operations?receipt_ids=${receiptId}`, {
    headers: { authorization: `Bearer ${token}` },
  });
  expect(response.ok(), await response.text()).toBe(true);
  const result = (await response.json()) as UploadOperationStatusResponse;
  return result.operations?.find((operation) => operation.receipt_id === receiptId);
}

async function userCanSeeAsset(
  request: APIRequestContext,
  token: string,
  filename: string,
  repositoryId?: string,
): Promise<boolean> {
  const response = await request.post("/api/v1/assets/list", {
    headers: { authorization: `Bearer ${token}` },
    data: {
      query: filename,
      search_type: "filename",
      filter: repositoryId ? { repository_id: repositoryId } : {},
      pagination: { limit: 50, offset: 0 },
      stack_mode: "expanded",
    },
  });
  expect(response.ok(), await response.text()).toBe(true);
  const result = (await response.json()) as QueryResponse;
  return (
    result.items?.some((item) => item.media_item?.primary_asset?.original_filename === filename) ??
    false
  );
}

async function expectSubjectLockout(
  requestAttempt: () => Promise<APIResponse>,
  expectedFailureStatus = 401,
): Promise<APIResponse> {
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    const response = await requestAttempt();
    expect(response.status(), `attempt ${attempt}`).toBe(expectedFailureStatus);
  }

  const blocked = await requestAttempt();
  expect(blocked.status()).toBe(429);
  expect(Number(blocked.headers()["retry-after"])).toBeGreaterThanOrEqual(1);
  return blocked;
}

test("@auth-hardening refresh-token replay revokes every refresh session for the user", async ({
  playwright,
  baseURL,
  workspace,
}) => {
  const firstRequest = await playwright.request.newContext({ baseURL });
  const secondRequest = await playwright.request.newContext({ baseURL });
  const replayRequest = await playwright.request.newContext({ baseURL });
  try {
    const firstDevice = await login(firstRequest, workspace);
    const firstRefreshCookie = await apiRefreshCookie(firstRequest);
    const secondDevice = await login(secondRequest, workspace);

    const rotatedFirstDevice = await expectAuth(await refresh(firstRequest, firstDevice.csrfToken));
    expect(await apiRefreshCookie(firstRequest)).not.toBe(firstRefreshCookie);

    // The rotated token is usable before the predecessor is replayed.
    const currentUser = await firstRequest.get("/api/v1/auth/me", {
      headers: { authorization: `Bearer ${rotatedFirstDevice.token}` },
    });
    expect(currentUser.ok(), await currentUser.text()).toBe(true);

    // Reusing the predecessor is treated as theft. The old cookie and its
    // matching CSRF proof are captured only by the test; neither was exposed to
    // browser JavaScript.
    expect(
      (
        await refreshWithCredential(replayRequest, firstRefreshCookie, firstDevice.csrfToken)
      ).status(),
    ).toBe(401);
    expect((await refresh(firstRequest, rotatedFirstDevice.csrfToken)).status()).toBe(401);
    expect((await refresh(secondRequest, secondDevice.csrfToken)).status()).toBe(401);

    // Short-lived access remains valid until expiry; the affected devices
    // simply cannot extend their sessions. A fresh password login recovers.
    const stillAuthenticated = await secondRequest.get("/api/v1/auth/me", {
      headers: { authorization: `Bearer ${secondDevice.token}` },
    });
    expect(stillAuthenticated.ok(), await stillAuthenticated.text()).toBe(true);

    const recovered = await login(firstRequest, workspace);
    expect((await refresh(firstRequest, recovered.csrfToken)).status()).toBe(200);
  } finally {
    await firstRequest.dispose();
    await secondRequest.dispose();
    await replayRequest.dispose();
  }
});

test("@auth-hardening browser logout clears local credentials and revokes its refresh token", async ({
  page,
  request,
  workspace,
}) => {
  await new LoginPage(page).signIn(workspace.username, workspace.password);

  const accountButton = page.getByRole("button", { name: workspace.username });
  await accountButton.click();

  const browserRefreshCookie = (await page.context().cookies()).find(
    (cookie) => cookie.name === "lumilio_refresh",
  );
  if (!browserRefreshCookie) throw new Error("authenticated browser has no refresh cookie");
  expect(browserRefreshCookie.httpOnly).toBe(true);
  const browserCSRFToken = await page.evaluate(() => window.localStorage.getItem("csrf_token"));
  if (!browserCSRFToken) throw new Error("authenticated browser has no CSRF proof");
  expect(
    await page.evaluate(() =>
      Object.keys(window.localStorage).some((key) => /refresh.*token/i.test(key)),
    ),
  ).toBe(false);

  const logoutResponsePromise = page.waitForResponse(
    (incoming) =>
      incoming.request().method() === "POST" &&
      new URL(incoming.url()).pathname === "/api/v1/auth/logout",
  );
  await page.getByRole("button", { name: t("auth.logout"), exact: true }).click();

  const logoutResponse = await logoutResponsePromise;
  expect(logoutResponse.ok()).toBe(true);
  await expect(page).toHaveURL(/\/login$/);

  expect(
    (await refreshWithCredential(request, browserRefreshCookie.value, browserCSRFToken)).status(),
  ).toBe(401);
  expect((await page.context().cookies()).some((cookie) => cookie.name === "lumilio_refresh")).toBe(
    false,
  );

  await expect
    .poll(() =>
      page.evaluate(() => Object.keys(window.localStorage).filter((key) => /token/i.test(key))),
    )
    .toEqual([]);
});

test("@auth-hardening browser session endpoints enforce origin and CSRF boundaries", async ({
  playwright,
  baseURL,
  workspace,
}) => {
  const sessionRequest = await playwright.request.newContext({ baseURL });
  const openAPIRequest = await playwright.request.newContext({ baseURL });
  try {
    const auth = await login(sessionRequest, workspace);

    const invalidCSRF = await sessionRequest.post("/api/v1/auth/refresh", {
      headers: { "x-csrf-token": "invalid-csrf-proof" },
    });
    expect(invalidCSRF.status()).toBe(403);

    const crossOriginRefresh = await sessionRequest.post("/api/v1/auth/refresh", {
      headers: {
        origin: "https://untrusted.example.test",
        "x-csrf-token": auth.csrfToken,
      },
    });
    expect(crossOriginRefresh.status()).toBe(403);
    expect(crossOriginRefresh.headers()["access-control-allow-origin"]).toBeUndefined();
    expect(crossOriginRefresh.headers()["access-control-allow-credentials"]).toBeUndefined();

    // Rejected requests do not consume or rotate the session.
    await expectAuth(await refresh(sessionRequest, auth.csrfToken));

    // Cross-origin API clients may use explicit Bearer credentials without
    // receiving browser-cookie privileges.
    const bearerResponse = await openAPIRequest.get("/api/v1/auth/me", {
      headers: {
        authorization: `Bearer ${auth.token}`,
        origin: "https://untrusted.example.test",
      },
    });
    expect(bearerResponse.ok(), await bearerResponse.text()).toBe(true);
    expect(bearerResponse.headers()["access-control-allow-origin"]).toBe("*");
    expect(bearerResponse.headers()["access-control-allow-credentials"]).toBeUndefined();
  } finally {
    await sessionRequest.dispose();
    await openAPIRequest.dispose();
  }
});

test("@auth-hardening authentication subjects lock out and recover without leaking credentials", async ({
  playwright,
  baseURL,
  request,
  workspace,
}, testInfo) => {
  const username = `rate${testInfo.parallelIndex}x${Date.now()}`;
  await register(request, username, workspace.password);

  const blockedLogin = await expectSubjectLockout(() =>
    request.post("/api/v1/auth/login", {
      data: { username, password: "Wrong-Password-2026!" },
    }),
  );
  expect(await blockedLogin.text()).not.toContain(username);

  const correctWhileLocked = await request.post("/api/v1/auth/login", {
    data: { username, password: workspace.password },
  });
  expect(correctWhileLocked.status()).toBe(429);

  const retryAfterSeconds = Number(blockedLogin.headers()["retry-after"]);
  await new Promise((resolve) => setTimeout(resolve, retryAfterSeconds * 1_000 + 250));
  await expectAuth(
    await request.post("/api/v1/auth/login", {
      data: { username, password: workspace.password },
    }),
  );

  await expectSubjectLockout(() =>
    request.post("/api/v1/auth/passkeys/login/options", {
      data: { username },
    }),
  );
  const invalidPasskeyToken = `invalid-passkey-${testInfo.parallelIndex}-${Date.now()}`;
  await expectSubjectLockout(() =>
    request.post("/api/v1/auth/passkeys/login/verify", {
      data: {
        challenge_token: invalidPasskeyToken,
        credential: {},
      },
    }),
  );
  const invalidMFAToken = `invalid-mfa-${testInfo.parallelIndex}-${Date.now()}`;
  await expectSubjectLockout(() =>
    request.post("/api/v1/auth/mfa/verify", {
      data: {
        mfa_token: invalidMFAToken,
        code: "000000",
        method: "totp",
      },
    }),
  );
  const refreshRequest = await playwright.request.newContext({ baseURL });
  const refreshReplayRequest = await playwright.request.newContext({ baseURL });
  try {
    const refreshUser = `refresh${testInfo.parallelIndex}x${Date.now()}`;
    const refreshAuth = await register(refreshRequest, refreshUser, workspace.password);
    const predecessorCookie = await apiRefreshCookie(refreshRequest);
    await expectAuth(await refresh(refreshRequest, refreshAuth.csrfToken));

    await expectSubjectLockout(() =>
      refreshWithCredential(refreshReplayRequest, predecessorCookie, refreshAuth.csrfToken),
    );
  } finally {
    await refreshRequest.dispose();
    await refreshReplayRequest.dispose();
  }
});

test("@auth-hardening exhausted session clears user A before user B data loads", async ({
  page,
  request,
  workspace,
}, testInfo) => {
  test.setTimeout(150_000);
  const privateFilename = `auth-isolation-${testInfo.parallelIndex}-${Date.now()}.jpg`;
  const uploadReceiptId = await uploadAsset(request, workspace, privateFilename);
  await expect
    .poll(
      async () =>
        (await uploadOperationStatus(request, workspace.token, uploadReceiptId))?.terminal ?? false,
      {
        message: `${privateFilename} upload operation should reach a terminal state for user A`,
        timeout: 120_000,
        intervals: [500, 1_000, 2_000],
      },
    )
    .toBe(true);
  const completedUpload = await uploadOperationStatus(request, workspace.token, uploadReceiptId);
  expect(completedUpload?.success, completedUpload?.error ?? completedUpload?.status).toBe(true);
  expect(
    await userCanSeeAsset(request, workspace.token, privateFilename, workspace.repositoryId),
  ).toBe(true);

  await new LoginPage(page).signIn(workspace.username, workspace.password);
  await page.goto("/assets");
  await page
    .getByLabel(t("assets.assetsPageHeader.scope.title"))
    .filter({ visible: true })
    .selectOption({ label: workspace.repositoryName });
  await expect(page.getByLabel(new RegExp(privateFilename, "i"))).toBeVisible({
    timeout: 30_000,
  });

  const userASession = await page.evaluate(() => ({
    token: window.localStorage.getItem("auth_token"),
    csrfToken: window.localStorage.getItem("csrf_token"),
  }));
  const userARefreshCookie = (await page.context().cookies()).find(
    (cookie) => cookie.name === "lumilio_refresh",
  );
  if (!userASession.token || !userASession.csrfToken || !userARefreshCookie) {
    throw new Error("user A browser session was not stored");
  }
  await page.evaluate(() => {
    window.localStorage.setItem(
      "lumilio.settings.assets_state",
      JSON.stringify({ query: "user-a-private-state" }),
    );
    window.localStorage.setItem("assets_state_v1", "user-a-legacy-private-state");
  });

  const revoke = await request.post("/api/v1/auth/logout", {
    headers: {
      cookie: `lumilio_refresh=${userARefreshCookie.value}`,
      "x-csrf-token": userASession.csrfToken,
    },
  });
  expect(revoke.ok(), await revoke.text()).toBe(true);
  await page.evaluate(() => window.localStorage.setItem("auth_token", "expired-access-token"));
  await page.reload();

  await expect(page).toHaveURL(/\/login$/, { timeout: 30_000 });
  await expect
    .poll(() =>
      page.evaluate(() =>
        Object.keys(window.localStorage).filter(
          (key) =>
            /token/i.test(key) ||
            key === "lumilio.settings.assets_state" ||
            key === "assets_state_v1",
        ),
      ),
    )
    .toEqual([]);

  const userB = `isolate${testInfo.parallelIndex}x${Date.now()}`;
  await register(request, userB, workspace.password);

  let releaseListRequest: (() => void) | undefined;
  const listRequestGate = new Promise<void>((resolve) => {
    releaseListRequest = resolve;
  });
  let markListRequestStarted: (() => void) | undefined;
  const listRequestStarted = new Promise<void>((resolve) => {
    markListRequestStarted = resolve;
  });
  await page.route("**/api/v1/assets/list", async (route) => {
    markListRequestStarted?.();
    await listRequestGate;
    await route.continue();
  });

  try {
    const listResponse = page.waitForResponse(
      (response) =>
        response.request().method() === "POST" &&
        new URL(response.url()).pathname === "/api/v1/assets/list",
    );
    await new LoginPage(page).signIn(userB, workspace.password, /\/assets$/);
    const userBToken = await page.evaluate(() => window.localStorage.getItem("auth_token"));
    if (!userBToken) throw new Error("user B browser session was not stored");
    expect(userBToken).not.toBe(userASession.token);
    await listRequestStarted;

    // While B's real response is held back, A's cached gallery must not render.
    await expect(page.getByLabel(new RegExp(privateFilename, "i"))).toHaveCount(0);

    releaseListRequest?.();
    const response = await listResponse;
    expect(response.ok(), await response.text()).toBe(true);
    await expect(page.getByLabel(new RegExp(privateFilename, "i"))).toHaveCount(0);
    expect(await userCanSeeAsset(request, userBToken, privateFilename)).toBe(false);
  } finally {
    releaseListRequest?.();
    await page.unroute("**/api/v1/assets/list");
  }
});
